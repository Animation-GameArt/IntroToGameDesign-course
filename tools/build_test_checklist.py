"""Builds Planning/Testing Checklist.md from the checklists in the guides.

Run it after changing any exercise, tutorial or "Building the Sample" guide:
    python3 tools/build_test_checklist.py
Items already ticked in the existing checklist stay ticked.
"""
import glob, os, re, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Planning", "Testing Checklist.md")
BASE = "https://github.com/Animation-GameArt/IntroToGameDesign-course/blob/main/"
TESTED_EXERCISES = ["Ex01", "Ex02", "Ex03", "Ex04"]  # tested before this checklist existed

def link(path):
    return BASE + urllib.parse.quote(os.path.relpath(path, ROOT).replace(os.sep, "/"))

def items(path):
    """The '- [ ]' lines from the guide's check section (the last section that has them)."""
    out, section, found = [], None, {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("## "):
            section = line[3:].strip()
        m = re.match(r"- \[[ xX]\] (.*)", line)
        if m:
            found.setdefault(section, []).append(m.group(1).strip())
    if not found:
        return None, []
    section = list(found)[-1]
    return section, found[section]

ticked = set()
if os.path.exists(OUT):
    for line in open(OUT, encoding="utf-8"):
        m = re.match(r"\s*- \[[xX]\] (.*)", line)
        if m:
            ticked.add(m.group(1).strip())

def box(text, done=False):
    return f"- [{'x' if done or text in ticked else ' '}] {text}"

def block(path, title, done=False):
    section, checks = items(path)
    lines = [f"### {title}", "", f"Guide: [{os.path.basename(path)[:-3]}]({link(path)}) — section *{section}*", ""]
    lines += [box(c, done) for c in checks]
    lines += [box(f"{title}: anything that failed is reported to Claude, with the Console message", done), ""]
    return lines

doc = ["---", 'title: "Testing Checklist"', "course: GAME 1303", "status: working", "audience: instructor",
       "tags:", "  - game1303", "  - instructor", "---", "",
       "# Testing Checklist", "",
       "**For the instructor.** Every check from the exercises, tutorials and kit samples, in the order to test them. "
       "Each item is copied from its guide's own checklist, so work through the guide and tick the items here as they pass. "
       "Report anything that fails to Claude with the Console message; fixes always come before new work.", "",
       "This page is generated by `tools/build_test_checklist.py`. Ticks are kept when it's rebuilt, so edit ticks here "
       "but edit the checks themselves in the guides.", "",
       "## 1. Before anything", "",
       box("Pull the template project; the Console shows no red errors (any compile error stops Play mode for the whole project)"),
       box("Every UI Document uses `CoursePanelSettings` (**Collin Game → Use Course Panel Settings in Open Scenes** fixes a scene)"),
       box("Kenney packs unzipped in `Assets/_Course/Art/Kenney`, and **Reapply Art Import Settings** run"), "",
       "## 2. Exercises", "",
       "Students meet these first, so they matter most. Ex 01–04 were tested before this list existed.", ""]

for path in sorted(glob.glob(os.path.join(ROOT, "Exercises", "Ex*.md"))):
    name = os.path.basename(path)[:-3]
    doc += block(path, name, done=name[:4] in TESTED_EXERCISES)

doc += ["## 3. 2.5D tutorials", ""]
for path in sorted(glob.glob(os.path.join(ROOT, "Tutorials", "*.md"))):
    doc += block(path, os.path.basename(path)[:-3])

doc += ["## 4. Kit samples", "",
        "The Platformer sample has a menu command (**Collin Game → Kit Samples → Build Platformer Sample**); play it, then go "
        "through its checks. The other kits are built by hand from their guides for now; Claude writes their menu commands "
        "once the Platformer one is confirmed. Building a sample by hand is itself the test of the kit's scripts and guide.", ""]
order = ["Platformer", "Physics Puzzle", "Top-Down Adventure", "Turn-Based Battle", "Arcade Classic",
         "Top-Down Shooter", "Endless Runner", "Grid Puzzle", "Tower Defense", "Management", "Farming", "Visual Novel"]
for kit in order:
    path = os.path.join(ROOT, "Kit Guides", f"{kit} Kit - Building the Sample.md")
    if os.path.exists(path):
        doc += block(path, f"{kit} Kit")
        doc += [box(f"{kit} Kit: sample committed and pushed with its .meta files"), ""]

doc += ["## 5. Before the semester", "",
        box("The whole student path on a lab computer: download the Release ZIP, unzip, open, import a kit package"),
        box("Each kit exported as a package and imported into a fresh copy of the template"), ""]

open(OUT, "w", encoding="utf-8").write("\n".join(doc))
n = sum(1 for l in doc if l.startswith("- ["))
print(f"Wrote {os.path.relpath(OUT, ROOT)}: {n} checks, {sum(1 for l in doc if l.startswith('- [x]'))} ticked")
